macro_rules! pin_project_either {
    ($id:ident, $($param:ident),+ $(,)?) => {
        // SAFETY: rama-core defines `$id` and implements neither `Unpin` (beyond the auto
        // impl) nor `Drop` for it; other crates cannot add either impl (orphan rule).
        unsafe impl<$($param),+> PinProjectEither for $id<$($param),+> {}
    };
}

impl_either!(pin_project_either);

#[macro_export]
#[doc(hidden)]
macro_rules! __impl_iterator_either {
    ($id:ident, $($param:ident),+ $(,)?) => {
        impl<$($param),+, Item> Iterator for $id<$($param),+>
        where
            $($param: Iterator<Item = Item>),+,
        {
            type Item = Item;

            fn next(&mut self) -> Option<Item> {
                match self {
                    $(
                        $id::$param(iter) => iter.next(),
                    )+
                }
            }

            fn size_hint(&self) -> (usize, Option<usize>) {
                match self {
                    $(
                        $id::$param(iter) => iter.size_hint(),
                    )+
                }
            }
        }
    };
}

