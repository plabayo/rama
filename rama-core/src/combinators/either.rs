/// Opt-in for the pin projection of a type generated by [`define_either!`].
///
/// [`define_either!`] provides `as_pin_mut`, and the `Future` impl built on it, only for
/// types that implement this trait; so do the impls of `impl_async_read_write_either!`.
///
/// # Safety
///
/// The implementor, which must be the crate that invoked [`define_either!`] for the type,
/// must ensure that for every instantiation of its type parameters the type has no `Unpin`
/// impl other than the auto-trait one and no `Drop` impl. A variant reached through
/// `Pin<&mut Self>` is then never moved before it is dropped (structural pinning).
pub unsafe trait PinProjectEither {}

/// Define an `Either`-like enum with one tuple variant per type parameter.
///
/// Pin projection (`as_pin_mut`) and the `Future` impl built on it require an
/// `unsafe impl` of [`PinProjectEither`] for the generated type, written by the
/// invoking crate:
///
/// ```
/// use core::{fmt, pin::Pin, task::Poll};
/// use rama_core::combinators::{PinProjectEither, define_either};
///
/// define_either!(MyEither, A, B);
///
/// // SAFETY: this crate implements neither `Unpin` nor `Drop` for `MyEither`.
/// unsafe impl<A, B> PinProjectEither for MyEither<A, B> {}
///
/// let mut fut = core::pin::pin!(MyEither::<_, core::future::Ready<u8>>::A(async { 1_u8 }));
/// let waker = core::task::Waker::noop();
/// let mut cx = core::task::Context::from_waker(&waker);
/// assert_eq!(fut.as_mut().poll(&mut cx), Poll::Ready(1));
/// ```
///
/// Without it there is no pin projection:
///
/// ```compile_fail,E0599
/// use core::{fmt, pin::Pin, task::Poll};
/// use rama_core::combinators::define_either;
///
/// define_either!(MyEither, A, B);
///
/// let mut either = core::pin::pin!(MyEither::<u8, u16>::A(1));
/// let _ = either.as_mut().as_pin_mut();
/// ```
#[macro_export]
#[doc(hidden)]
macro_rules! __define_either {
    ($id:ident, $($param:ident),+ $(,)?) => {
        /// A type to allow you to use multiple types as a single type.
        ///
        /// and will delegate the functionality to the type that is wrapped in the `Either` type.
        /// To keep it easy all wrapped types are expected to work with the same inputs and outputs.
        ///
        /// You can use [`crate::combinators::impl_either`] to
        /// implement the `Either` type for the available number of type parameters
        /// on your own Trait implementations.
        #[derive(Debug, Clone)]
        pub enum $id<$($param),+> {
            $(
                /// one of the Either variants
                $param($param),
            )+
        }

        impl<$($param),+> fmt::Display for $id<$($param),+>
        where
            $($param: fmt::Display),+
        {
            fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
                match self {
                    $(
                        $id::$param(s) => write!(f, "{}", s),
                    )+
                }
            }
        }


        impl<$($param),+> $id<$($param),+>
        where
            $id<$($param),+>: $crate::combinators::PinProjectEither,
        {
            /// Convert `Pin<&mut Either<A, B>>` to `Either<Pin<&mut A>, Pin<&mut B>>`,
            /// pinned projections of the inner variants.
            ///
            /// This is the pin-projection used to implement pinned traits (e.g.
            /// `Future`/`AsyncRead`) for `Either`; it is public so downstream
            /// crates can implement their own pinned traits over `Either` too.
            pub fn as_pin_mut(self: Pin<&mut Self>) -> $id<$(Pin<&mut $param>),+> {
                // SAFETY: `get_unchecked_mut` requires that the value is not moved out
                // of the returned `&mut Self`: it is only matched to borrow one field.
                let this = unsafe { self.get_unchecked_mut() };
                match this {
                    $(
                        // SAFETY: `Pin::new_unchecked` requires `*inner` to stay pinned
                        // until dropped. It is a field of the pinned `Self`; by the
                        // `PinProjectEither` contract `Self` has only the auto `Unpin` impl
                        // and no `Drop` impl, and no API gives an unpinned `&mut` to it from
                        // `Pin<&mut Self>`.
                        Self::$param(inner) => $id::$param(unsafe { Pin::new_unchecked(inner) }),
                    )+
                }
            }
        }

        impl<$($param),+, Output> Future for $id<$($param),+>
        where
            $($param: Future<Output = Output>),+,
            $id<$($param),+>: $crate::combinators::PinProjectEither,
        {
            type Output = Output;

            fn poll(self: Pin<&mut Self>, cx: &mut core::task::Context<'_>) -> Poll<Self::Output> {
                match self.as_pin_mut() {
                    $(
                        $id::$param(fut) => fut.poll(cx),
                    )+
                }
            }
        }
    };
}

